// 7. Seeded Vouchers with Persistent Local Storage Layer
const VOUCHER_STORAGE_KEY = 'owm.vouchers.store';

function loadStoredVouchers(companyId: string): Voucher[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(`${VOUCHER_STORAGE_KEY}_${companyId}`);
    if (raw) return JSON.parse(raw);
  } catch {
    // fallback
  }
  return [];
}

function saveStoredVouchers(companyId: string, vouchers: Voucher[]) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(`${VOUCHER_STORAGE_KEY}_${companyId}`, JSON.stringify(vouchers));
  } catch {
    // ignore
  }
}

