export function createMockVoucher(companyId: string, input: CreateVoucherInput): Voucher {
  const current = getMockVouchers(companyId);
  const nextNum = current.length + 1;
  const prefix = input.voucherTypeCode.slice(0, 3).toUpperCase();
  const voucherNumber = `${prefix}-${String(nextNum).padStart(4, '0')}`;

  const totalAmount = input.entries.reduce((acc, e) => acc + (e.debit || 0), 0);

  const newVoucher: Voucher = {
    id: `${companyId}-vch-${Date.now()}`,
    companyId,
    voucherTypeId: `${companyId}-vt-${input.voucherTypeCode.toLowerCase()}`,
    voucherNumber,
    voucherDate: input.voucherDate || new Date().toISOString().split('T')[0],
    referenceNumber: input.referenceNumber || '',
    narration: input.narration || '',
    status: 'POSTED',
    amount: String(totalAmount || 100000),
    createdBy: 'Managing Owner',
    postedAt: new Date().toISOString(),
    entries: input.entries.map((ent, idx) => ({
      id: `ent-new-${Date.now()}-${idx}`,
      ledgerId: `${companyId}-led-${ent.ledgerCode.toLowerCase()}`,
      ledgerCode: ent.ledgerCode,
      debit: String(ent.debit || 0),
      credit: String(ent.credit || 0),
      narration: ent.narration || '',
    })),
  };

  const stored = loadStoredVouchers(companyId);
  saveStoredVouchers(companyId, [newVoucher, ...stored]);
  return newVoucher;
}

