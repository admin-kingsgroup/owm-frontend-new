/**
 * The currencies offered wherever one is chosen — a company's base, a business's reporting
 * currency, the currency master — so nobody types a three-letter code.
 *
 * A currency's code is not a code to mint: it is the ISO 4217 one, and the rest of the world reads
 * it. Picking from a list is what removes the typing, and also the typo — "UDS" would otherwise
 * become a currency record of its own. The set is the ones a firm here plausibly deals in, not all
 * of ISO 4217; one missing is a line added below, not a change anywhere else.
 */
export interface WorldCurrency {
  code: string;
  symbol: string;
  name: string;
}

